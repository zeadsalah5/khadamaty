## أختار قدرة قد إيه (كام حصان)؟

القدرة بتتقاس بالحصان، وهي **أهم معيار** في الاختيار. القاعدة البسيطة: كل ما المساحة أكبر، احتجت قدرة أكبر. بس المساحة لوحدها مش كفاية — في عوامل بتزوّد الحِمل:

- **ارتفاع السقف:** سقف عالي = هوا أكتر محتاج تبريد.
- **تعرّض المكان للشمس:** واجهة شمس طول النهار بتحتاج قدرة أعلى.
- **عدد الناس والأجهزة:** كل جسم أو جهاز بيطلّع حرارة (كمبيوتر، مطبخ قريب...) بيزوّد الحِمل.
- **التهوية والعزل:** مكان كويس العزل بيحافظ على البرودة فبيحتاج أقل.

**اختيار القدرة الغلط بيكلّفك في الاتجاهين:**

- **أصغر من اللازم:** الجهاز بيفضل شغّال على طول ومايوصلش للبرودة، فبيتعب ويستهلك كتير.
- **أكبر من اللازم:** بيبرّد بسرعة ويفصل بسرعة بشكل متكرر، وده بيصرف كهربا زيادة وبيأثّر على الرطوبة.

