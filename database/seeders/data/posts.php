- **المساحة وارتفاع السقف:** المساحة الأكبر والسقف العالي بيحتاجوا قدرة أكبر.
- **تعرّض المكان للشمس:** أوضة واجهتها شمس طول النهار بتحتاج قدرة أعلى من أوضة مظلّلة.
