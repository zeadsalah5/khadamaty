## يعني إيه إن التكييف "بيفصل"؟

التكييف الطبيعي بيفصل الكمبروسر لما الأوضة توصل للدرجة اللي انت طالبها، وبعدين يرجّع يشتغل لما الحرارة تعلى شوية تاني — ده شغل عادي وصحي. لكن اللي بنتكلم عنه هنا مختلف: التكييف بيقفل بعد دقايق قليلة من التشغيل، أو بيفصل ويرجّع بشكل متكرر وسريع من غير ما الأوضة تبرد. النوع ده من الفصل بيبقى علامة إن فيه حاجة محتاجة مراجعة.

## الأسباب الشائعة وراء فصل التكييف

في أسباب كتير ممكن تخلّي التكييف يفصل لوحده، وأشهرها:

- **الفلاتر متسخة ومسدودة:** لما الفلتر يتوسّخ، الهوا مابيعدّيش كويس، والوحدة بتسخن وبتفصل كإجراء حماية. ده من أكتر الأسباب وأبسطها.
- **الوحدة الخارجية مش لاقية تهوية:** لو الكوندنسر (الوحدة الخارجية) محطوط في مكان ضيّق أو حواليه أتربة وزرع كتير، الحرارة مابتطلعش منه، فبيسخن ويفصل.
- **مشكلة في غاز التبريد:** نقص الفريون أو تسريب فيه بيخلّي الضغط مش مظبوط، والتكييف ممكن يفصل عشان يحمي نفسه. دي محتاجة فني يكشف ويحدد مكان التسريب.
- **حسّاس الحرارة (الثرموستات) مش مظبوط:** لو الحسّاس بايظ أو مكانه غلط، ممكن يقرأ الحرارة غلط ويفصل التكييف بدري.
- **مشاكل كهربائية:** زي كابل مش مثبّت كويس أو لوحة تحكّم فيها عطل. دي حاجة حسّاسة ولازم متخصص يشوفها.

## حاجات بسيطة تقدر تجرّبها بنفسك

