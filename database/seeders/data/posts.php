## إيه أنواع التكييفات الأساسية؟

قبل ما تختار، خليك عارف الأنواع اللي قدامك:

- **سبليت (Split):** وحدة داخلية جوّه وخارجية برّه. الأكثر انتشاراً في البيوت، هادي وبيبرّد كويس. محتاج تأسيس مواسير نحاس وصرف.
