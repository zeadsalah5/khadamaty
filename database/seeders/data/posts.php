## ساعد التكييف بالعزل

التكييف بيتعب أكتر لو البرودة بتتسرّب برّه. حاجات بسيطة بتساعد:

- اقفل الشبابيك والأبواب كويس وانت مشغّل التكييف.
- استخدم ستاير تحجب الشمس المباشرة في أوقات الذروة.
- سدّ أي فتحات بتدخّل هوا سخن من برّه.

كل ده بيخلّي الأوضة تحافظ على برودتها، فالتكييف يشتغل أقل.

