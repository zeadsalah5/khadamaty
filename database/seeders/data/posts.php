## الكباس بيعمل إيه في التكييف؟

الكباس (الكمبروسر) هو **قلب دورة التبريد** — وظيفته إنه يضغط غاز الفريون ويحرّكه في الدورة عشان يحصل التبريد. موجود في الوحدة الخارجية. لو الكباس وقف أو ضعف، التكييف ممكن يشتغل (المروحة تلف) بس **مايبرّدش** أو يبرّد ضعيف جداً.

## علامات إن فيه مشكلة في الكباس

- التكييف شغّال والمروحة بتلف بس **مفيش تبريد** أو تبريد ضعيف جداً.
- **صوت غير معتاد** من الوحدة الخارجية (طنين عالي، طقطقة).
- التكييف **بيفصل بسرعة ومتكرر** بعد دقايق من التشغيل.
- الوحدة الخارجية **بتحاول تشتغل وبتفصل** (الكباس بيطقّ ويفصل).

لو لاحظت تبريد ضعيف، ابدأ بـ [التكييف مش بيبرّد](/blog/ac-not-cooling) لأن مش كل ضعف تبريد سببه الكباس — ممكن يكون غاز أو فلاتر.

## إمتى الكباس يتصلّح وإمتى يتغيّر؟

| الحالة | الأرجح |
|---|---|
| عطل في الكاباستور/الريليه/الأوفرلود | **إصلاح** (تغيير القطعة) |
| مشكلة كهربا أو توصيلات | **إصلاح** |
| الكباس مقفول/محروق كهربائياً | **تغيير** غالباً أوفر |
