"الحصان" هو وحدة بنقيس بيها قدرة التبريد في التكييف. كل ما زاد عدد الأحصنة، زادت قدرة الجهاز على تبريد مساحة أكبر. لكن القدرة مش بس على المساحة — فيه عوامل تانية بتفرق، زي تعرّض الأوضة للشمس وعدد الناس والأجهزة اللي جوّه.

