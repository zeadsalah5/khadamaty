- **كونسيلد (Concealed):** بيتخبّى في السقف الجبس وبيوزّع الهوا من فتحات. مناسب للتشطيب الفاخر والمساحات المفتوحة، وتركيبه وصيانته متخصّصين أكتر.
- **مركزي (Central):** منظومة كاملة بتبرّد الوحدة أو المبنى كله. للمساحات الكبيرة جداً، وتكلفته وصيانته أعلى.

