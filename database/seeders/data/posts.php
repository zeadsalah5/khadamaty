شحن الفريون سعره بيعتمد على **نوع الغاز وكميته**، وعلى إذا كان فيه تسريب محتاج كشف وإصلاح الأول. مهم: الشحن من غير ما نكشف سبب نقص الغاز بيكون حل مؤقت — لو فيه تسريب لازم يتصلّح. (TODO: صاحب الموقع يحدّد نطاق سعر الشحن حسب نوع وكمية الغاز). اعرف أكتر عن [شحن الفريون](/services/ac-gas-refill).

## وتكلفة التركيب؟

التركيب بيعتمد على **طول مواسير النحاس والصرف، تجهيز المكان، ونوع الوحدة**. لو محتاج تمديد مواسير طويلة أو تأسيس إضافي، ده بيأثر على التكلفة. (TODO: صاحب الموقع يحدّد نطاق سعر التركيب ومتى تنطبق تكلفة مواسير إضافية). التفاصيل في [تركيب التكييف](/services/ac-installation).

## إزاي أتجنّب المفاجآت في السعر؟

1. اطلب **سعر مبدئي** وقت الحجز حسب الخدمة والجهاز.
2. خلّي الفني **يعاين ويقولك التكلفة التقريبية قبل ما يبدأ**.
3. ماتوافقش على أي قطعة أو شغل إضافي من غير ما تعرف سعره الأول.
4. الدفع بيكون **بعد الشغل** وبعد ما تتأكد إن كل حاجة تمام.

