1. **نضّف الفلتر:** اقفل التكييف، افتح الوحدة الداخلية، واطلّع الفلتر. لو شايفه مليان أتربة، اغسله بميّه فاترة وسيبه ينشف كويس قبل ما ترجّعه. ده لوحده بيحل نسبة كبيرة من المشاكل.
