## قائمة الاستلام: 10 حاجات تراجعها

### 1. نوع المواسير
لازم تكون **نحاس**، مش ألومنيوم ولا خليط. النحاس بيبان لونه في الأطراف. اسأل عن المقاس، واتأكد إنه مناسب لقدرة الجهاز اللي هيتركب.

### 2. ماسورتين لكل جهاز
خط رفيع وخط تخين لكل تكييف، وكل واحد له مساره.

### 3. العزل على كل ماسورة لوحدها
العزل المشترك اللي بيلف الماسورتين مع بعض غلط، لأن الحرارة بتنتقل بينهم. لازم **كل ماسورة معزولة لوحدها** على الطول كله، من غير فراغات عند اللفّات.

### 4. مفيش ثني حاد
المواسير لازم تلف بانحناء ناعم. الثني الحاد أو «المكسور» بيضيّق مجرى الغاز.

### 5. أطراف مقفولة
أطراف المواسير عند مكان الوحدة الداخلية والخارجية **مقفولة أو مكبوسة** عشان التراب والرطوبة مايدخلوش لحد التركيب.

### 6. ميل الصرف
خرطوم الصرف لازم ينزل طول الوقت من مكان الوحدة الداخلية لحد نقطة الصرف. **مفيش أي طلعة** في النص. صب شوية مية من أول الخرطوم واتأكد إنها خرجت من آخره.

### 7. نقطة الصرف
الصرف رايح فين؟ لازم يكون لمكان صرف حقيقي، مش على حيطة الجيران أو على الواجهة.

### 8. كابل الكهربا
كابل بمقاس مناسب بين مكان الوحدتين، وخط منفصل من اللوحة بقاطع للتكييف. فيشة على سلك مشترك ماتنفعش.

### 9. اختبار الضغط
اطلب من الفني **اختبار ضغط بالنيتروجين** للمواسير قبل الدفن، وسيبه فترة وشوف العدّاد ماينزلش. ده أهم بند في القائمة كلها، لأنه الوحيد اللي بيكشف لحام ضعيف أو وصلة مش محكمة.

### 10. الأماكن مطابقة للخطة
مكان كل وحدة داخلية وخارجية زي ما اتفقتوا. غيّرت رأيك؟ دلوقتي أرخص وقت تغيّر فيه.

