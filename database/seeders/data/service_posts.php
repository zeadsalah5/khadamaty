4. **اغسلها بمية فاترة** من الناحية العكسية للتراب. لو فيها دهون، استخدم صابون خفيف.
5. **سيبها تنشف في الضل.** ماتحطّهاش في الشمس المباشرة، وماتنشّفهاش بسشوار سخن.
6. **رجّعها مكانها** واقفل الغطا.

**ماتعملش:** ماترشّش مية جوه الوحدة، وماتشغّلش الجهاز من غير فلاتر، وماتستخدمش مواد كيميائية قوية.

اقرا التفاصيل العامة في [طريقة غسيل وتنظيف التكييف في البيت](/blog/how-to-clean-ac).

