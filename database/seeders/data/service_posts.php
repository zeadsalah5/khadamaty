## الجيران: صوت ومية

في العمارات اللازقة في بعض، التكييف ممكن يبقى سبب مشاكل:

### الصوت والاهتزاز
- **الوحدة الخارجية بتهتز على الحامل** فالصوت ينتقل للحيطة ولشقة الجيران.
- **الحل:** قواعد مطاط تحت الوحدة، وشدّ مسامير الحامل، وتنظيف المروحة الخارجية. اقرا [التكييف بيعمل صوت عالي](/blog/ac-noise).

### المية اللي بتنقّط
- **خرطوم الصرف ساعات بينزّل على بلكونة الجيران أو على المارّة.**
- **الحل:** الفني يوجّه الصرف لماسورة صرف أو مكان مناسب. ولو المية بتنقّط من الوحدة الداخلية، اقرا [مياه بتنقّط من الوحدة الداخلية](/blog/ac-water-leak).

