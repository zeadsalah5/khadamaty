### 4. الوحدة الخارجية
- غسيل المكثّف من الناحية العكسية للتراب.
- فحص المروحة وريشها.
- فحص الكابستور والكونتاكتور والوصلات وشدّ المسامير.
- التأكد إن الحامل ثابت.

